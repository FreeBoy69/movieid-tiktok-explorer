// Builds data/shortfilm-prompts.json: the genre video templates from
// jnMetaCode/ai-shortfilm-prompts (MIT, templates/ only) as prompt library
// entries in the "video" category. That repo's prompts/ directory is All
// Rights Reserved and is never read.
//
//   node scripts/build-shortfilm-prompts.mjs [path/to/templates/index.json]
import fs from "node:fs";
import path from "node:path";

const REPO = "https://github.com/jnMetaCode/ai-shortfilm-prompts";
const COMMIT = "328fd831ff6f35db1a320ac2af70411e7dc8303b";
const OUT = path.resolve("data/shortfilm-prompts.json");
// Generalised from a third party's All Rights Reserved material; left out to be safe.
const SKIP = new Set(["15s-transformation"]);
const TAGS = {
  "科幻 / 动作": ["sci-fi", "action"],
  萌宠: ["pets", "animals"],
  "广告 / 产品": ["commercial", "product"],
  风格化: ["stylized"],
  "音乐 / 舞蹈": ["music", "dance"],
  "旅行 / 风光": ["travel", "landscape"],
  "剧情 / 短剧": ["drama", "story"],
  "时尚 / 美妆": ["fashion", "beauty"],
  美食: ["food"],
};

const source = process.argv[2];
const index = source
  ? JSON.parse(fs.readFileSync(source, "utf8"))
  : await (await fetch(`https://raw.githubusercontent.com/jnMetaCode/ai-shortfilm-prompts/${COMMIT}/templates/index.json`)).json();

const title = (text) =>
  String(text)
    .replace(/^Worked Example\s*[—-]\s*/i, "")
    .replace(/\s*\([^)]*[㐀-鿿][^)]*\)/g, "")
    .trim();
// "Original worked example by jnMetaCode (MIT). Applies the 5-stage structure to a teaser trailer — …" → "A teaser trailer — …"
const summary = (text) => {
  const body = String(text)
    .replace(/\s*[(（][^)）]*[\u3400-\u9fff][^)）]*[)）]?/g, "")
    .replace(/\b([a-z0-9-]+)\.md\b/g, (_, id) => id.replace(/-/g, " "))
    .replace(/^Original worked example by jnMetaCode \(MIT\)\.\s*/i, "")
    .replace(/^(Applies|Demonstrates) the 5-stage structure (applied )?to\s*/i, "")
    .replace(/^The 5-stage structure applied to\s*/i, "")
    .replace(/\s+/g, " ");
  const sentence = body.match(/^.+?[.!?](\s|$)/)?.[0] || body;
  const clipped = sentence.trim().slice(0, 220);
  return clipped.charAt(0).toUpperCase() + clipped.slice(1);
};
// Markdown headings, bold, and fences stripped so the prompt pastes cleanly into a video model.
const plain = (text) =>
  String(text)
    .replace(/```[a-z]*\n?/g, "")
    .replace(/^#{1,6}\s*(.+)$/gm, "$1:")
    .replace(/\*\*(.+?)\*\*/g, "$1")
    .replace(/(^|\s)\*(\S[^*]*?)\*(?=\s|[.,:;]|$)/g, "$1$2")
    .replace(/`([^`]+)`/g, "$1")
    .replace(/^\s*---\s*$/gm, "")
    .replace(/Negative prompt \(Seedance \/ Kling — paste into the dedicated field\)/, "Negative prompt")
    .replace(/::$/gm, ":")
    // Undo the source's hard wrapping: indented or lowercase lines continue the line above.
    .replace(/\n[ \t]{2,}(?=\S)/g, " ")
    .replace(/(?<!:)\n(?=[a-z(\"'{—–])/g, " ")
    .replace(/[ \t]{2,}/g, " ")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
const fill = (text, variables) =>
  variables.reduce((result, { name, example }) => result.replaceAll(`{{${name}}}`, String(example).replace(/^"|"$/g, "")), text);

const prompts = index.templates
  .filter((template) => template.lang === "en" && template.kind === "genre" && template.hasPrompt && template.license === "MIT" && !SKIP.has(template.id))
  .map((template) => {
    const raw = plain(template.prompt);
    return {
      id: `shortfilm-${template.id}`,
      title: title(template.title),
      act: template.id.replace(/-/g, " "),
      contributor: template.author,
      type: "TEXT",
      categories: ["video"],
      relevance: 4,
      summary: summary(template.description),
      snippet: fill(raw, template.variables || []),
      tags: [...(TAGS[template.category] || []), "short film", "text-to-video"],
      prompt: template.variables?.length ? raw : undefined,
      // Blanks the template gallery lets the creator fill before using the prompt.
      variables: template.variables?.length
        ? template.variables.map(({ name, example }) => ({ name, example: String(example).replace(/^"|"$/g, "") }))
        : undefined,
      // Covers generated by scripts/generate-template-thumbnails.mjs, when there is one.
      image: fs.existsSync(path.resolve(`public/assets/templates/${template.id}.webp`)) ? `/assets/templates/${template.id}.webp` : undefined,
      url: `${REPO}/blob/${COMMIT}/${template.file}`,
      license: "MIT",
      sourceName: "ai-shortfilm-prompts",
    };
  });

fs.writeFileSync(
  OUT,
  `${JSON.stringify({ source: { repo: REPO, commit: COMMIT, license: "MIT", builtAt: new Date().toISOString() }, prompts }, null, 1)}\n`,
);
console.log(`wrote ${prompts.length} video prompts to ${path.relative(process.cwd(), OUT)}`);
